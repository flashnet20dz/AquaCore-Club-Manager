export interface ClubMetricsSnapshot {
  النادي: string;
  التاريخ: string;
  المنخرطون: {
    الإجمالي: number;
    حسب_حالة_الدفع: Record<string, number>;
    حسب_الجنس: Record<string, number>;
    حسب_نوع_الاشتراك: Record<string, number>;
  };
  المالية_بالدينار: {
    إيراد_اليوم: number;
    دفعات_اليوم: number;
    إيراد_هذا_الشهر: number;
    إيراد_الشهر_الماضي: number;
  };
  الحضور: {
    اليوم: number;
    هذا_الأسبوع: number;
    الأسبوع_الماضي: number;
    آخر_30_يوم: number;
  };
  الغائبون_21_يوماً_أو_أكثر: number;
  الجدول_الأسبوعي: {
    أيام_السباحة_المفعلة: number;
    الفترات_المفعلة: Array<{ الفترة: string; السعة_القصوى: number }>;
    توزيع_المنخرطين_على_الأيام: Record<string, number>;
    أكثر_الفترات_ازدحاماً: Array<{ الفترة: string; المنخرطون: number; السعة: number | string }>;
  };
  إغلاقات_قادمة_أو_جارية: number;
  قائمة_الانتظار: number;
  العمال: number;
}

function formatDA(num: number): string {
  return new Intl.NumberFormat("fr-DZ").format(Math.round(num)) + " دج";
}

export function generateLocalAIResponse(question: string, m: ClubMetricsSnapshot): string {
  const q = question.toLowerCase().trim();

  // 1) التحية والترحيب
  if (/^(مرحبا|سلام|أهلا|اهلا|صباح الخير|مساء الخير|السلام عليكم)/i.test(q) && q.length < 30) {
    return `أهلاً بك! أنا المساعد الذكي لإدارة نادي «${m.النادي}».
أنا جاهز للإجابة عن أي استفسار يخص إحصائيات المنخرطين، المداخيل المالية، نسب الحضور، مؤشرات التسرب، وجدول الحصص. كيف يمكنني مساعدتك اليوم؟`;
  }

  // 2) أسئلة الدفع والمنخرطين غير المسددين
  if (/لم يدفع|غير مدفوع|غير المسدد|الديون|مستحق|حالة الدفع|كم دفع|المدفوع/i.test(q)) {
    const unpaid = m.المنخرطون.حسب_حالة_الدفع["لم يدفع"] || 0;
    const paid = m.المنخرطون.حسب_حالة_الدفع["مدفوع"] || 0;
    const insOnly = m.المنخرطون.حسب_حالة_الدفع["تأمين فقط"] || 0;
    const exempt = m.المنخرطون.حسب_حالة_الدفع["معفى"] || 0;
    const total = m.المنخرطون.الإجمالي;
    const collectionRate = total > 0 ? Math.round((paid / total) * 100) : 0;

    return `حالة تسديد الاشتراكات بنادي «${m.النادي}» (${m.التاريخ}):

• إجمالي المنخرطين: ${total} منخرط.
• المسددون بالكامل: ${paid} منخرط (${collectionRate}% نسبة التحصيل).
• غير المسددين (لم يدفع): ${unpaid} منخرط(ة).
• مسددو التأمين فقط: ${insOnly} منخرط.
${exempt > 0 ? `• المعفيون من الرسوم: ${exempt} منخرط.\n` : ""}
💡 توصية: يُنصح بإرسال تذكيرات عبر رسائل WhatsApp الجماعية للمنخرطين غير المسددين لتسوية وضعياتهم قبل بداية الأسبوع القادم.`;
  }

  // 3) أسئلة المداخيل والمالية ومقارنة الشهور
  if (/إيراد|ايراد|مداخيل|المالية|دخل|الشهر الماضي|هذا الشهر|مقارنة|مبيعات|مبالغ/i.test(q)) {
    const cur = m.المالية_بالدينار.إيراد_هذا_الشهر;
    const prev = m.المالية_بالدينار.إيراد_الشهر_الماضي;
    const todayRev = m.المالية_بالدينار.إيراد_اليوم;
    const todayPayments = m.المالية_بالدينار.دفعات_اليوم;

    let growthText = "";
    if (prev > 0) {
      const diff = cur - prev;
      const pct = Math.round((diff / prev) * 100);
      if (pct > 0) {
        growthText = `بارتفاع قدره +${pct}% (+${formatDA(diff)}) مقارنة بالشهر السابق.`;
      } else if (pct < 0) {
        growthText = `بانخفاض قدره ${pct}% (${formatDA(diff)}) مقارنة بالشهر السابق.`;
      } else {
        growthText = `وهو مطابق تماماً لإيراد الشهر السابق.`;
      }
    } else {
      growthText = `(الشهر السابق: 0 دج أو بداية التسجيل).`;
    }

    return `التقرير المالي لنادي «${m.النادي}»:

• إيراد اليوم: ${formatDA(todayRev)} (عبر ${todayPayments} عملية دفع).
• إيراد هذا الشهر حتى الآن: ${formatDA(cur)} — ${growthText}
• إيراد الشهر الماضي كاملاً: ${formatDA(prev)}.

💡 يمكنك الاطلاع على التحليل المحاسبي المفصل من «المركز المالي» ← تبويب «التحليل المالي».`;
  }

  // 4) أسئلة الحضور ومؤشر الغياب / خطر التسرب (أنقذ هؤلاء)
  if (/غائب|غياب|تسرب|3 أسابيع|21 يوم|انقذ|أنقذ|حضور|الحضور/i.test(q)) {
    const churn = m.الغائبون_21_يوماً_أو_أكثر;
    const attToday = m.الحضور.اليوم;
    const attWeek = m.الحضور.هذا_الأسبوع;
    const attPrevWeek = m.الحضور.الأسبوع_الماضي;

    return `تقرير الحضور ونشاط السباحين بنادي «${m.النادي}»:

• حضور اليوم: ${attToday} عملية دخول مسجلة.
• حضور هذا الأسبوع: ${attWeek} زيارة (مقارنة بـ ${attPrevWeek} الأسبوع الماضي).
• منخرطون غائبون لأكثر من 21 يوماً (خطر تسرب): ${churn} منخرط(ة).

⚠️ تنبيه إداري: المنخرطون الغائبون لأكثر من 3 أسابيع يمثلون خطراً كبيراً لعدم التجديد. نوصي بتفعيل ميزة «أنقذ هؤلاء» من لوحة التحكم لإرسال رسائل تشجيعية عبر WhatsApp لاستعادتهم للمسبح.`;
  }

  // 5) أسئلة الازدحام وفترات السباحة والجدول
  if (/فترة|فترات|ازدحام|الجدول|حصص|حصة|سعة|ايام|أيام|السبت|الأحد|الجمعة|ضغط/i.test(q)) {
    const slots = m.الجدول_الأسبوعي.أكثر_الفترات_ازدحاماً;
    const dayLoads = m.الجدول_الأسبوعي.توزيع_المنخرطين_على_الأيام;
    
    // Sort days by subscriber count
    const sortedDays = Object.entries(dayLoads).sort((a, b) => b[1] - a[1]);
    const topDay = sortedDays[0];

    let slotsText = "";
    if (slots.length > 0) {
      slotsText = slots
        .map((s, i) => `${i + 1}. فترة «${s.الفترة}»: ${s.المنخرطون} منخرطاً (السعة: ${s.السعة}).`)
        .join("\n");
    } else {
      slotsText = "لا توجد فترات مسجلة حالياً.";
    }

    return `تحليل جدول السباحة والضغط الأسبوعي:

• اليوم الأكثر إقبالاً: يوم «${topDay ? topDay[0] : "—"}» بمجموع ${topDay ? topDay[1] : 0} منخرطاً مسجلاً.
• الفترات الأكثر ازدحاماً:
${slotsText}

💡 توجيه: الفترات المزدحمة تقترب من حد الأمان الاستيعابي؛ يُفضل توجيه الاشتراكات الجديدة نحو الفترات الأقل ضغطاً لتحقيق توازن تشغيلي مثالي وجودة تدريب أعلى.`;
  }

  // 6) طلب التحليل العام والتوصيات
  if (/حلل|أداء|توصيات|نصائح|رأي|تقييم|اقتراحات/i.test(q)) {
    const total = m.المنخرطون.الإجمالي;
    const unpaid = m.المنخرطون.حسب_حالة_الدفع["لم يدفع"] || 0;
    const churn = m.الغائبون_21_يوماً_أو_أكثر;
    const curRev = m.المالية_بالدينار.إيراد_هذا_الشهر;
    const prevRev = m.المالية_بالدينار.إيراد_الشهر_الماضي;
    const isGrowing = curRev >= prevRev;

    return `خلاصة تحليل أداء نادي «${m.النادي}»:
يسجل النادي قاعدة مشتركين تبلغ ${total} منخرطاً، مع أداء مالي ${isGrowing ? "إيجابي ومستقر" : "يحتاج إلى تسريع وتيرة التحصيل"} بإيراد شهري قدره ${formatDA(curRev)}.

التوصيات العملية المقترحة:
1. تحصيل المتأخرات: التواصل الفوري مع ${unpaid} منخرط لم يسددوا اشتراكاتهم بعد.
2. استعادة الغائبين: متابعة ${churn} منخرط غائبين منذ أكثر من 3 أسابيع قبل انتهاء صلاحية اشتراكاتهم.
3. التوزيع الميداني: إعادة توجيه المسجلين الجدد نحو الفترات الصباحية لتخفيف الضغط عن المسائية.
4. الرقابة المالية: تدقيق يومي لصندوق المقبوضات ومطابقة دفتر العمليات.`;
  }

  // 7) أسئلة الموظفين، قائمة الانتظار، الإغلاقات
  if (/عمال|موظف|حراس|مدرب|انتظار|صيانة|إغلاق|اغلاق/i.test(q)) {
    return `معلومات الدعم التشغيلي لنادي «${m.النادي}»:

• عدد العمال والمدربين المسجلين: ${m.العمال} موظفاً.
• المسجلون في قائمة الانتظار: ${m.قائمة_الانتظار} طلباً بانتظار توفر أماكن.
• الإغلاقات الجارية أو القادمة للصيانة: ${m.إغلاقات_قادمة_أو_جارية} إغلاق(ات).`;
  }

  // 8) استفسار عام / غير محدد
  const total = m.المنخرطون.الإجمالي;
  const curRev = m.المالية_بالدينار.إيراد_هذا_الشهر;
  const unpaid = m.المنخرطون.حسب_حالة_الدفع["لم يدفع"] || 0;
  const attWeek = m.الحضور.هذا_الأسبوع;

  return `نظرة شاملة وموجزة عن وضع النادي بتاريخ اليوم (${m.التاريخ}):

• النادي: «${m.النادي}».
• إجمالي المشتركين: ${total} منخرط (${unpaid} بانتظار السداد).
• إيراد هذا الشهر: ${formatDA(curRev)}.
• إجمالي الحضور هذا الأسبوع: ${attWeek} زيارة.
• منخرطون بخطر التسرب (>21 يوم غياب): ${m.الغائبون_21_يوماً_أو_أكثر} منخرطاً.

يمكنك سؤالي عن تفاصيل المداخيل، المشتركين غير المسددين، الفترات الأكثر ازدحاماً، أو طلب توصيات مخصصة.`;
}

export function generateLocalInsights(m: any): string {
  const total = m.إجمالي_المنخرطين || 0;
  const unpaid = m.غير_مدفوعين || 0;
  const churn = m.منخرطون_غائبون_21يوم_أو_أكثر || 0;
  const curRev = m.إيراد_هذا_الشهر_دج || 0;
  const prevRev = m.إيراد_الشهر_الماضي_دج || 0;
  const revDiff = curRev - prevRev;
  const trend = revDiff >= 0 ? "إيجابي" : "يحتاج إلى تحسين وتيرة التحصيل";

  return `أداء النادي مستقر مع قاعدة نشطة تضم ${total} منخرطاً، والمسار المالي ${trend} بإيراد شهري قدره ${formatDA(curRev)}.

التوصيات العملية لهذا الأسبوع:
1. تحصيل الاشتراكات: التواصل مع ${unpaid} منخرطاً غير مسددين عبر رسائل تذكير لطيفة لتسوية وضعياتهم.
2. استعادة الغائبين: متابعة ${churn} منخرطاً غائبين منذ أكثر من 3 أسابيع عبر WhatsApp قبل فقدانهم.
3. التوزيع الأسبوعي: توجيه المشتركين في فئة «${m.أكثر_نوع_اشتراك}» نحو الفترات الأقل ضغطاً لتحسين جودة التدريب.`;
}

