/** دور عنصر «الاسم الرسمي الكامل» — يُولَّد آلياً من إعدادات النادي إن كان المحتوى فارغاً */
export const CLUB_FULL_NAME_ROLE = "clubFullName";

/** بادئة الجمعية الرسمية تُلحق باسم النادي */
export const ASSOC_PREFIX = "الجمعية الرياضية الهاوية";

/** السلسلة الافتراضية لاسم النادي (كما في إعدادات النادي الافتراضية) */
export const DEFAULT_CLUB_CHAIN = "النادي الهاوي متعدد الرياضات - الرائد سعيدة - فرع السباحة";

/** حجم الشعار الموحّد (بكسل) — ثابت في كل صفحات الموقع والمطبوعات حتى لا يقفز ولا يتغير حجمه */
export const UNIFIED_LOGO_SIZE = 70;

/**
 * الاسم الرسمي الكامل في سطر واحد:
 * «الجمعية الرياضية الهاوية» + سلسلة اسم النادي من الإعدادات.
 * لا يُضاعف البادئة إن كانت موجودة أصلاً (لا تكرار للكلمات).
 */
export function composeClubFullName(settings?: { clubName?: string | null }): string {
  const name = (settings?.clubName || "").trim();
  const base = name || DEFAULT_CLUB_CHAIN;
  if (base.startsWith(ASSOC_PREFIX)) return base;
  return `${ASSOC_PREFIX} ${base}`;
}

/** إصدار بنية الترويسة — يُستخدم لترقية الإعدادات القديمة المخزنة تلقائياً */
export const ENTETE_VERSION = 2;
